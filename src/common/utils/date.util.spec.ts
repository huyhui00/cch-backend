/// <reference types="jest" />
// TypeScript 6 ไม่ดึง @types/jest เข้ามาให้อัตโนมัติ ต้องอ้างถึงตรงนี้เหมือน spec ตัวอื่น

import { addDays, addMonths, daysUntil, toDateOnly, todayAsDateOnly } from './date.util';

/**
 * สูตรวันที่ของระยะประกัน (BR-06)
 *
 * เป็นฟังก์ชันบริสุทธิ์ล้วน ๆ ไม่แตะฐานข้อมูล แต่เป็นจุดที่ผิดแล้วเสียเงินจริง —
 * ประกันยาวหรือสั้นกว่าที่ตกลงกันไว้แค่วันเดียวก็มีผลต่อการตัดสินว่าเคสไหนฟรี
 */

describe('addMonths', () => {
  it('บวกเดือนตรงไปตรงมาเมื่อวันที่ปลายทางมีอยู่จริง', () => {
    expect(addMonths('2026-09-08', 12)).toBe('2027-09-08');
    expect(addMonths('2026-09-08', 6)).toBe('2027-03-08');
    expect(addMonths('2026-09-08', 1)).toBe('2026-10-08');
  });

  it('ข้ามปีได้ถูกต้อง', () => {
    expect(addMonths('2026-12-15', 1)).toBe('2027-01-15');
    expect(addMonths('2026-11-30', 24)).toBe('2028-11-30');
  });

  it('หนีบลงมาเป็นวันสุดท้ายของเดือน เมื่อเดือนปลายทางสั้นกว่า', () => {
    // ถ้าใช้ Date.setMonth() ตรง ๆ จะได้ 2026-03-03 เพราะล้นจาก 31 ก.พ. ที่ไม่มีจริง
    // ผลคือระยะประกันยาวเกินที่ตกลงไว้สามวันโดยไม่มีใครสังเกต
    expect(addMonths('2026-01-31', 1)).toBe('2026-02-28');
    expect(addMonths('2026-03-31', 1)).toBe('2026-04-30');
    expect(addMonths('2026-08-31', 6)).toBe('2027-02-28');
  });

  it('รู้จักปีอธิกสุรทิน', () => {
    expect(addMonths('2028-01-31', 1)).toBe('2028-02-29');
    expect(addMonths('2028-02-29', 12)).toBe('2029-02-28');
  });

  it('บวกศูนย์เดือนแล้วได้วันเดิม', () => {
    expect(addMonths('2026-09-08', 0)).toBe('2026-09-08');
  });

  it('เติมศูนย์หน้าเลขเดือนและวันเสมอ', () => {
    // ถ้าคืน '2027-1-5' ออกไป การเทียบสตริงกับวันที่อื่นจะเพี้ยนทันที
    expect(addMonths('2026-10-05', 3)).toBe('2027-01-05');
  });
});

describe('daysUntil', () => {
  function dateOnlyOffsetByDays(days: number): string {
    const date = new Date();
    date.setDate(date.getDate() + days);
    return toDateOnly(date);
  }

  it('วันนี้เหลือศูนย์วัน', () => {
    expect(daysUntil(todayAsDateOnly())).toBe(0);
  });

  it('นับวันข้างหน้าเป็นบวก', () => {
    expect(daysUntil(dateOnlyOffsetByDays(30))).toBe(30);
  });

  it('นับวันที่ผ่านไปแล้วเป็นลบ', () => {
    // ประกันที่หมดไปแล้วต้องบอกได้ว่าหมดมากี่วัน ไม่ใช่ตัดเหลือศูนย์
    expect(daysUntil(dateOnlyOffsetByDays(-5))).toBe(-5);
  });
});

describe('toDateOnly', () => {
  it('ตัดเวลาทิ้งเหลือแค่วัน', () => {
    expect(toDateOnly(new Date(2026, 8, 8, 23, 45, 0))).toBe('2026-09-08');
  });

  it('เติมศูนย์หน้าเลขเดือนและวันหลักเดียว', () => {
    expect(toDateOnly(new Date(2026, 0, 5, 0, 0, 0))).toBe('2026-01-05');
  });
});

/**
 * ใช้คิดขอบล่าง/ขอบบนของรอบโควตา MA (Phase 8) และช่วงวันของหน้าจอ "สัญญาใกล้หมดอายุ"
 */
describe('addDays', () => {
  it('บวกวันภายในเดือนเดียวกัน', () => {
    expect(addDays('2026-09-09', 5)).toBe('2026-09-14');
  });

  it('ลบวันข้ามเดือนได้', () => {
    // ใช้จริงตอนหาวันสุดท้ายของรอบ = วันเริ่มรอบถัดไป ลบหนึ่งวัน
    expect(addDays('2026-10-01', -1)).toBe('2026-09-30');
  });

  it('ข้ามปีได้', () => {
    expect(addDays('2026-12-31', 1)).toBe('2027-01-01');
  });

  it('รู้จักปีอธิกสุรทิน', () => {
    expect(addDays('2028-02-28', 1)).toBe('2028-02-29');
    expect(addDays('2026-02-28', 1)).toBe('2026-03-01');
  });

  it('บวกศูนย์วันได้ค่าเดิม', () => {
    expect(addDays('2026-09-09', 0)).toBe('2026-09-09');
  });

  it('เติมศูนย์หน้าเลขเดือนและวันหลักเดียว', () => {
    expect(addDays('2026-01-09', -1)).toBe('2026-01-08');
  });
});
